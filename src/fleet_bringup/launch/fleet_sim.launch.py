"""Multi-robot Gazebo simulation with one configurable TurtleBot3 fleet."""
import os
import tempfile
import xml.etree.ElementTree as ET

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import (DeclareLaunchArgument, ExecuteProcess, GroupAction,
                            OpaqueFunction, SetEnvironmentVariable, TimerAction)
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node, SetParameter


SPAWN_POSES = ((0.0, 0.0), (1.5, 0.0), (0.0, 1.5), (1.5, 1.5), (3.0, 0.0))


def _enabled(context, name):
    return LaunchConfiguration(name).perform(context).lower() in ('1', 'true', 'yes', 'on')


def _robot_names(context):
    configured = LaunchConfiguration('robots').perform(context).strip()
    if configured:
        names = tuple(item.strip() for item in configured.split(',') if item.strip())
    else:
        count = int(LaunchConfiguration('robot_count').perform(context))
        names = tuple(f'robot{index}' for index in range(1, count + 1))
    if not 1 <= len(names) <= len(SPAWN_POSES) or len(set(names)) != len(names):
        raise RuntimeError('robots must contain 1 to 5 unique robot names')
    if any(not name.replace('_', '').isalnum() for name in names):
        raise RuntimeError('robot names may only contain letters, numbers and underscores')
    return names


def _write_bridge_config(path, names):
    lines = [
        '# Generated by fleet_sim.launch.py for the selected robots.',
        '- ros_topic_name: "/clock"',
        '  gz_topic_name: "/clock"',
        '  ros_type_name: "rosgraph_msgs/msg/Clock"',
        '  gz_type_name: "gz.msgs.Clock"',
        '  direction: GZ_TO_ROS',
    ]
    topics = (
        ('odom', 'nav_msgs/msg/Odometry', 'gz.msgs.Odometry', 'GZ_TO_ROS'),
        ('scan', 'sensor_msgs/msg/LaserScan', 'gz.msgs.LaserScan', 'GZ_TO_ROS'),
        ('imu', 'sensor_msgs/msg/Imu', 'gz.msgs.IMU', 'GZ_TO_ROS'),
        ('joint_states', 'sensor_msgs/msg/JointState', 'gz.msgs.Model', 'GZ_TO_ROS'),
        ('camera/image', 'sensor_msgs/msg/Image', 'gz.msgs.Image', 'GZ_TO_ROS'),
        ('camera/camera_info', 'sensor_msgs/msg/CameraInfo', 'gz.msgs.CameraInfo', 'GZ_TO_ROS'),
        ('cmd_vel', 'geometry_msgs/msg/Twist', 'gz.msgs.Twist', 'ROS_TO_GZ'),
    )
    for name in names:
        for topic, ros_type, gz_type, direction in topics:
            lines.extend((
                f'- ros_topic_name: "/{name}/{topic}"',
                f'  gz_topic_name: "/{name}/{topic}"',
                f'  ros_type_name: "{ros_type}"',
                f'  gz_type_name: "{gz_type}"',
                f'  direction: {direction}',
            ))
        lines.extend((
            '- ros_topic_name: "/tf"',
            f'  gz_topic_name: "/{name}/tf"',
            '  ros_type_name: "tf2_msgs/msg/TFMessage"',
            '  gz_type_name: "gz.msgs.Pose_V"',
            '  direction: GZ_TO_ROS',
        ))
    with open(path, 'w', encoding='utf-8') as stream:
        stream.write('\n'.join(lines) + '\n')


def _prefixed_description(text, name):
    root = ET.fromstring(text)
    root.set('name', name)
    for element in root.iter():
        if element.tag == 'link':
            element.set('name', name + '_' + element.get('name'))
        elif element.tag == 'joint':
            element.set('name', name + '_' + element.get('name'))
            for reference in ('parent', 'child'):
                node = element.find(reference)
                if node is not None:
                    node.set('link', name + '_' + node.get('link'))
    return ET.tostring(root, encoding='unicode')


def _write_generated_file(prefix, suffix, content):
    path = os.path.join(tempfile.gettempdir(), f'{prefix}_{os.getpid()}{suffix}')
    with open(path, 'w', encoding='utf-8') as stream:
        stream.write(content)
    return path


def _setup(context):
    bringup = get_package_share_directory('fleet_bringup')
    names = _robot_names(context)
    poses = {name: SPAWN_POSES[index] for index, name in enumerate(names)}
    models_dir = os.path.join(bringup, 'models')
    with open(os.path.join(models_dir, 'robot1', 'model.sdf'), encoding='utf-8') as stream:
        model_template = stream.read()
    urdf_path = os.path.join(bringup, 'urdf', 'turtlebot3_burger_fleet.urdf')
    with open(urdf_path, encoding='utf-8') as stream:
        urdf_text = stream.read()
    with open(os.path.join(bringup, 'config', 'nav2_robot1.yaml'), encoding='utf-8') as stream:
        nav2_template = stream.read()
    last_nav2_start = 10.0 + 10.0 * (len(names) - 1)
    agent_start = max(26.0, last_nav2_start + 6.0)
    manager_start = agent_start + 4.0

    bridge_yaml = _write_generated_file('fleet_bridge', '.yaml', '')
    _write_bridge_config(bridge_yaml, names)
    tb3_models = os.path.join(get_package_share_directory('turtlebot3_gazebo'), 'models')
    world_file = os.path.join(bringup, 'worlds', 'fleet_tasks.sdf')
    map_yaml = os.path.join(bringup, 'maps', 'fleet_map.yaml')
    actions = [
        SetEnvironmentVariable('GZ_SIM_RESOURCE_PATH', models_dir + ':' + tb3_models),
        SetParameter(name='use_sim_time', value=True),
        GroupAction([
            SetEnvironmentVariable('LIBGL_ALWAYS_SOFTWARE', '1'),
            ExecuteProcess(cmd=['gz', 'sim', '-r', '-s', '-v2', world_file], output='screen'),
        ]),
        Node(package='ros_gz_bridge', executable='parameter_bridge',
             parameters=[{'config_file': bridge_yaml}], output='screen'),
        Node(package='nav2_map_server', executable='map_server', name='fleet_map_server',
             parameters=[{'yaml_filename': map_yaml}], output='screen'),
        Node(package='nav2_lifecycle_manager', executable='lifecycle_manager',
             name='lifecycle_manager_map',
             parameters=[{'autostart': True, 'node_names': ['fleet_map_server']}],
             output='screen'),
    ]
    if _enabled(context, 'gui'):
        actions.append(GroupAction([
            SetEnvironmentVariable('LIBGL_ALWAYS_SOFTWARE', '1'),
            ExecuteProcess(cmd=['gz', 'sim', '-g', '-v2'], output='screen'),
        ]))

    def nav2_params(name):
        return _write_generated_file(f'fleet_nav2_{name}', '.yaml',
                                     nav2_template.replace('robot1', name))

    def nav2_node(name, package, executable, node_name, extra_parameters=None):
        parameters = [nav2_params(name)]
        if extra_parameters:
            parameters.append(extra_parameters)
        return Node(
            package=package, executable=executable, name=node_name, namespace=name,
            parameters=parameters,
            remappings=[('/tf', '/tf'), ('/tf_static', '/tf_static'),
                        (f'/{name}/map', '/map')], output='screen')

    for index, name in enumerate(names):
        x, y = poses[name]
        model_file = _write_generated_file(
            f'fleet_{name}', '.sdf', model_template.replace('robot1', name))
        actions.extend((
            Node(package='robot_state_publisher', executable='robot_state_publisher',
                 name=name + '_state_publisher',
                 parameters=[{'robot_description': _prefixed_description(urdf_text, name)}],
                 remappings=[('joint_states', name + '/joint_states'),
                             ('robot_description', name + '/robot_description')], output='screen'),
            Node(package='ros_gz_sim', executable='create',
                 arguments=['-world', 'fleet', '-file', model_file, '-name', name,
                            '-x', str(x), '-y', str(y), '-z', '0.05'], output='screen'),
        ))
        if _enabled(context, 'nav2'):
            actions.append(TimerAction(period=10.0 + 10.0 * index, actions=[
                nav2_node(name, 'nav2_amcl', 'amcl', 'amcl', {
                    'set_initial_pose': True, 'initial_pose.x': x, 'initial_pose.y': y,
                    'initial_pose.z': 0.0, 'initial_pose.yaw': 0.0}),
                nav2_node(name, 'nav2_controller', 'controller_server', 'controller_server'),
                nav2_node(name, 'nav2_planner', 'planner_server', 'planner_server'),
                nav2_node(name, 'nav2_behaviors', 'behavior_server', 'behavior_server'),
                nav2_node(name, 'nav2_bt_navigator', 'bt_navigator', 'bt_navigator'),
                nav2_node(name, 'nav2_lifecycle_manager', 'lifecycle_manager',
                          'lifecycle_manager_navigation', {'service_timeout': 20.0}),
            ]))
        if _enabled(context, 'perception'):
            actions.append(TimerAction(period=6.0, actions=[Node(
                package='fleet_perception', executable='perception_node', name='perception_node',
                namespace=name,
                parameters=[{'robot_id': name, 'world_frame': 'map',
                             'target_width': 0.2, 'max_range': 5.0,
                             'publish_debug_image': False}],
                output='screen')]))
        if _enabled(context, 'agent'):
            actions.append(TimerAction(period=agent_start, actions=[Node(
                package='fleet_agent', executable='robot_agent', name='robot_agent',
                namespace=name,
                parameters=[{'robot_id': name, 'world_frame': 'map', 'standoff': 0.6,
                             'pre_dock_margin': 0.8, 'nav_timeout': 150.0,
                             'dock_timeout': 45.0, 'target_lost_timeout': 5.0,
                             'detection_stale_ms': 2000}], output='screen')]))

    if _enabled(context, 'manager'):
        actions.append(TimerAction(period=manager_start, actions=[Node(
            package='fleet_manager', executable='fleet_manager_node', name='fleet_manager',
            parameters=[{'robot_ids': list(names), 'dispatch_robot_ids': list(names),
                         'standoff': 0.6, 'publish_markers': True,
                         # 多车时偶发超时/心跳抖动很常见：放宽看门狗并给 3 次重排
                         'max_retries': 3, 'retry_cooldown': 5.0,
                         'heartbeat_timeout': 8.0, 'nav_timeout': 165.0,
                         'dock_timeout': 220.0}], output='screen')]))
    if _enabled(context, 'rviz'):
        actions.append(TimerAction(period=6.0, actions=[GroupAction([
            SetEnvironmentVariable('LIBGL_ALWAYS_SOFTWARE', '0'),
            Node(package='rviz2', executable='rviz2', name='fleet_rviz',
                 arguments=['-d', os.path.join(bringup, 'config', 'fleet.rviz')], output='screen'),
        ])]))
    if _enabled(context, 'monitor'):
        actions.append(TimerAction(
            period=manager_start + 4.0,
            actions=[Node(package='fleet_gui', executable='fleet_monitor',
                          name='fleet_monitor', output='screen')]))
    return actions


def generate_launch_description():
    return LaunchDescription([
        DeclareLaunchArgument('robot_count', default_value='2',
                              description='Number of robots, from 1 to 5.'),
        DeclareLaunchArgument('robots', default_value='',
                              description='Comma-separated IDs; overrides robot_count.'),
        DeclareLaunchArgument('gui', default_value='false'),
        DeclareLaunchArgument('rviz', default_value='true'),
        DeclareLaunchArgument('nav2', default_value='true'),
        DeclareLaunchArgument('perception', default_value='true'),
        DeclareLaunchArgument('agent', default_value='true'),
        DeclareLaunchArgument('manager', default_value='true'),
        DeclareLaunchArgument('monitor', default_value='false'),
        OpaqueFunction(function=_setup),
    ])
